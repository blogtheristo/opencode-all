#!/usr/bin/env node
/**
 * inject-faq-jsonld.mjs — AEO FAQ structured data injector.
 *
 * Reads curated Q&A from dws10.com/config/faq.json and injects a schema.org
 * FAQPage <script type="application/ld+json"> block into each listed page's
 * <head>, so AI answer engines and Google rich results can surface DWS answers.
 *
 * Content is curated (judgment); injection is deterministic (code). The block is
 * wrapped in FAQ-JSONLD:START / FAQ-JSONLD:END markers, so re-runs REPLACE the
 * managed block in place (idempotent) rather than appending duplicates. Each page
 * is written to both the root folder and its landing-pages mirror in the same run
 * (Dual Folder Sync Rule).
 *
 * Usage:
 *   node scripts/on-deploy/inject-faq-jsonld.mjs           write blocks
 *   node scripts/on-deploy/inject-faq-jsonld.mjs --check   report only, no writes (CI)
 *
 * Exit code: 0 on success; 1 if --check finds drift, or on malformed input.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const CHECK_ONLY = process.argv.includes('--check');
const SRC = 'dws10.com';
const MIRROR = 'landing-pages/dws10-com';
const START =
  '<!-- FAQ-JSONLD:START (generated by scripts/on-deploy/inject-faq-jsonld.mjs — edit dws10.com/config/faq.json) -->';
const END = '<!-- FAQ-JSONLD:END -->';

const jsonEsc = (s) => JSON.stringify(String(s)); // safe JSON string literal incl. quotes

function buildBlock(entry) {
  const questions = entry.faqs
    .map(
      (f) => `        {
          "@type": "Question",
          "name": ${jsonEsc(f.q)},
          "acceptedAnswer": { "@type": "Answer", "text": ${jsonEsc(f.a)} }
        }`,
    )
    .join(',\n');
  const ld = `      {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": [
${questions}
        ]
      }`;
  return `${START}\n    <script type="application/ld+json">\n${ld}\n    </script>\n    ${END}`;
}

/** Insert or replace the managed block in an HTML string. Returns new HTML or null on failure. */
function applyBlock(html, block) {
  const startIdx = html.indexOf(START);
  if (startIdx !== -1) {
    const endIdx = html.indexOf(END, startIdx);
    if (endIdx === -1) return null; // corrupt markers
    const before = html.slice(0, startIdx);
    const after = html.slice(endIdx + END.length);
    return before + block + after;
  }
  // No markers yet — insert before </head>.
  const headClose = html.search(/<\/head>/i);
  if (headClose === -1) return null;
  return html.slice(0, headClose) + `    ${block}\n  ` + html.slice(headClose);
}

function processFile(relPath, block, results) {
  const abs = path.join(ROOT, relPath);
  if (!fs.existsSync(abs)) {
    results.push({ relPath, status: 'MISSING' });
    return;
  }
  const html = fs.readFileSync(abs, 'utf8');
  const next = applyBlock(html, block);
  if (next === null) {
    results.push({ relPath, status: 'NO-ANCHOR' });
    return;
  }
  const changed = next !== html;
  if (changed && !CHECK_ONLY) fs.writeFileSync(abs, next, 'utf8');
  results.push({ relPath, status: changed ? (CHECK_ONLY ? 'WOULD-WRITE' : 'WROTE') : 'unchanged' });
}

function main() {
  const cfgPath = path.join(ROOT, SRC, 'config/faq.json');
  let cfg;
  try {
    cfg = JSON.parse(fs.readFileSync(cfgPath, 'utf8'));
  } catch (err) {
    console.error(`! cannot read ${cfgPath}: ${err.message}`);
    process.exit(1);
  }

  const results = [];
  for (const [pagePath, entry] of Object.entries(cfg.pages || {})) {
    if (!entry.faqs || entry.faqs.length === 0) {
      console.warn(`! skip ${pagePath}: no faqs`);
      continue;
    }
    const block = buildBlock(entry);
    // Validate the generated JSON parses before writing it into a page.
    const raw = block.slice(block.indexOf('{'), block.lastIndexOf('}') + 1);
    try {
      JSON.parse(raw);
    } catch (err) {
      console.error(`! ${pagePath}: generated invalid JSON-LD: ${err.message}`);
      process.exit(1);
    }
    processFile(path.join(SRC, pagePath), block, results);
    processFile(path.join(MIRROR, pagePath), block, results);
    console.log(`• ${pagePath} (${entry.faqs.length} Q&A)`);
  }

  const problems = results.filter((r) => r.status === 'MISSING' || r.status === 'NO-ANCHOR');
  const changed = results.filter((r) => ['WROTE', 'WOULD-WRITE'].includes(r.status));
  for (const r of results) console.log(`  [${r.status}] ${r.relPath}`);
  console.log(
    `\n${changed.length} file(s) ${CHECK_ONLY ? 'would change' : 'written'}, ${problems.length} problem(s), ${results.length} total.`,
  );

  if (problems.length) process.exit(1);
  if (CHECK_ONLY && changed.length) process.exit(1);
}

main();
