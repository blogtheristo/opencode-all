#!/usr/bin/env bash
# Weekly Housekeeping Audit — DGX Spark primary runtime.
#
# Mirrors .github/workflows/housekeeping-weekly.yml. Auto-discovered by
# infrastructure/dgx-spark/day-runner.sh (runs once per week on Sunday).
#
# Performs five checks and creates a single GitHub issue with the report:
#   1. Public path .md enforcement (CLAUDE.md rule 5)
#   2. Learn/ folder staleness
#   3. Branch hygiene (unmerged / merged remote branches)
#   4. Workflow health summary
#   5. docs/archive/ inventory
#
# Requirements on DGX:
#   - `gh` CLI configured with a PAT that has `issues:write` on this repo.
#     The day-runner runs under admin100; `gh auth status` must succeed.
#   - Repo synced to /home/admin100/dws6 (or wherever day-runner.sh sets $REPO_ROOT).

set -euo pipefail

REPO_ROOT="${REPO_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}"
cd "$REPO_ROOT"

REPORT="$(mktemp)"
trap 'rm -f "$REPORT"' EXIT

DATE="$(date -u +%Y-%m-%d)"
STATUS="PASS"

# ─── CHECK 1: Public path .md enforcement ───────────────────────────────────
{
  echo "## Public Path .md Audit"
  echo
} > "$REPORT"

MD_FILES="$(find dws10.com dws6.com onelifetime.world landing-pages \
  -name "*.md" -type f 2>/dev/null || true)"

if [ -z "$MD_FILES" ]; then
  echo "**Status:** PASS — No .md files found in public deployment paths." >> "$REPORT"
else
  COUNT="$(echo "$MD_FILES" | wc -l)"
  STATUS="FAIL"
  {
    echo "**Status:** FAIL — Found $COUNT .md files in public paths!"
    echo
    echo '```'
    echo "$MD_FILES"
    echo '```'
  } >> "$REPORT"
fi

# ─── CHECK 2: Learn/ folder staleness ───────────────────────────────────────
{
  echo
  echo "---"
  echo "## Learn/ Folder Audit"
  echo
} >> "$REPORT"

if [ ! -d "Learn" ]; then
  echo "**Status:** WARN — Learn/ folder not found." >> "$REPORT"
else
  HTML_COUNT="$(find Learn -name "*.html" -type f | wc -l)"
  MD_COUNT="$(find Learn -name "*.md" -type f | wc -l)"
  VERSIONED="$(find Learn -name "*_v*.html" -type f | wc -l)"
  STALE="$(find Learn -name "*.html" -type f -mtime +30 | wc -l)"
  {
    echo "| Metric | Count |"
    echo "|--------|-------|"
    echo "| HTML files (total) | $HTML_COUNT |"
    echo "| Versioned HTML files | $VERSIONED |"
    echo "| Markdown source files | $MD_COUNT |"
  } >> "$REPORT"
  if [ "$STALE" -gt 0 ]; then
    echo "" >> "$REPORT"
    echo "**Stale HTMLs (>30 days old):** $STALE files may need regeneration." >> "$REPORT"
  fi
fi

# ─── CHECK 3: Branch hygiene ────────────────────────────────────────────────
{
  echo
  echo "---"
  echo "## Branch Hygiene"
  echo
} >> "$REPORT"

REMOTE_BRANCHES="$(git branch -r --no-merged origin/main 2>/dev/null | grep -v HEAD | wc -l || echo 0)"
MERGED_BRANCHES="$(git branch -r --merged origin/main 2>/dev/null | grep -v HEAD | grep -v main | wc -l || echo 0)"
{
  echo "| Metric | Count |"
  echo "|--------|-------|"
  echo "| Unmerged remote branches | $REMOTE_BRANCHES |"
  echo "| Merged remote branches (can clean) | $MERGED_BRANCHES |"
} >> "$REPORT"

# ─── CHECK 4: Workflow health summary ───────────────────────────────────────
{
  echo
  echo "---"
  echo "## Workflow Health"
  echo
} >> "$REPORT"

TOTAL="$(find .github/workflows -name "*.yml" -type f | wc -l)"
SCHEDULED="$(grep -rl "schedule:" .github/workflows/ | wc -l)"
ON_PR="$(grep -rl "pull_request:" .github/workflows/ | wc -l)"
MANUAL="$(grep -rl "workflow_dispatch:" .github/workflows/ | wc -l)"
{
  echo "| Metric | Count |"
  echo "|--------|-------|"
  echo "| Total workflows | $TOTAL |"
  echo "| Scheduled (cron) | $SCHEDULED |"
  echo "| PR-triggered | $ON_PR |"
  echo "| Manual dispatch enabled | $MANUAL |"
} >> "$REPORT"

# ─── CHECK 5: docs/archive/ inventory ───────────────────────────────────────
{
  echo
  echo "---"
  echo "## Archive Inventory"
  echo
} >> "$REPORT"

if [ -d "docs/archive" ]; then
  for dir in docs/archive/*/; do
    if [ -d "$dir" ]; then
      DIRNAME="$(basename "$dir")"
      COUNT="$(find "$dir" -type f | wc -l)"
      echo "| \`$DIRNAME/\` | $COUNT files |" >> "$REPORT"
    fi
  done
else
  echo "**Status:** No docs/archive/ folder found." >> "$REPORT"
fi

# ─── Create or update GitHub issue ──────────────────────────────────────────
TITLE="Housekeeping Audit ${DATE} [${STATUS}]"
BODY_FILE="$(mktemp)"
trap 'rm -f "$REPORT" "$BODY_FILE"' EXIT

{
  echo "# Weekly Housekeeping Audit Report"
  echo
  echo "**Date:** ${DATE}"
  echo "**Triggered by:** dgx-spark cron"
  echo
  cat "$REPORT"
  echo
  echo "---"
  echo "*Generated by scripts/weekly/housekeeping-audit.sh (DGX Spark primary)*"
} > "$BODY_FILE"

if command -v gh >/dev/null 2>&1; then
  gh issue create \
    --title "$TITLE" \
    --body-file "$BODY_FILE" \
    --label "housekeeping,automated" \
    || echo "[housekeeping-audit] gh issue create failed; report follows:" && cat "$BODY_FILE"
else
  echo "[housekeeping-audit] gh CLI not installed; printing report to stdout:"
  cat "$BODY_FILE"
fi
