#!/usr/bin/env bash
# price-list-quarterly-gate.sh
#
# Runs DAILY under scripts/daily/ (DGX Spark day-runner auto-discovers).
# Acts only on the first day of each calendar quarter (Jan 1, Apr 1, Jul 1, Oct 1),
# regenerating the stamped price-list HTML snapshot for the new quarter.
#
# What it does on a quarter-start day:
#   1. Derives the new stamp (e.g. "2026.Q3") and valid-until date.
#   2. Updates priceList.version, stampQuarter, stampDate, validUntil, nextReviewDate
#      in dws10.com/config/products.json AND landing-pages/dws10-com/config/products.json.
#   3. Appends a changeLog entry.
#   4. Runs scripts/gen-price-list-html.cjs → writes
#      price-list/versions/price-list-v<version>.html in both folders.
#   5. Commits + pushes to the current branch (feature branches only; main is gated
#      by existing repo hooks).
#
# What it does NOT do: send emails. Email dispatch is RED-zone (human required).
# Run scripts/send-price-list-email.ts manually after reviewing the snapshot.
#
# Any other day: exits quietly.
#
# Idempotent: if today's quarter already matches the stored stampQuarter,
# the script detects it's already up to date and exits without committing.

set -euo pipefail

REPO_ROOT="${REPO_ROOT:-$(git -C "$(dirname "$0")/../.." rev-parse --show-toplevel 2>/dev/null || echo "$(cd "$(dirname "$0")/../.." && pwd)")}"
cd "${REPO_ROOT}"

TODAY="$(date -u +%Y-%m-%d)"
MONTH="$(date -u +%m)"
DAY="$(date -u +%d)"
YEAR="$(date -u +%Y)"

# Quarter-start gate: only act on Jan 1 / Apr 1 / Jul 1 / Oct 1.
if [ "${DAY}" != "01" ]; then
  exit 0
fi
case "${MONTH}" in
  01|04|07|10) ;;
  *) exit 0 ;;
esac

# Map month → quarter
case "${MONTH}" in
  01) Q=1; STAMP_DATE="${YEAR}-01-01"; VALID_UNTIL="${YEAR}-03-31"; NEXT_REVIEW="${YEAR}-04-01" ;;
  04) Q=2; STAMP_DATE="${YEAR}-04-01"; VALID_UNTIL="${YEAR}-06-30"; NEXT_REVIEW="${YEAR}-07-01" ;;
  07) Q=3; STAMP_DATE="${YEAR}-07-01"; VALID_UNTIL="${YEAR}-09-30"; NEXT_REVIEW="${YEAR}-10-01" ;;
  10) Q=4; STAMP_DATE="${YEAR}-10-01"; VALID_UNTIL="${YEAR}-12-31"
      NEXT_YEAR=$((YEAR + 1)); NEXT_REVIEW="${NEXT_YEAR}-01-01" ;;
  *)  exit 0 ;;
esac

NEW_VERSION="${YEAR}.Q${Q}"
NEW_STAMP_QUARTER="Q${Q} ${YEAR}"

CANON="dws10.com/config/products.json"
MIRROR="landing-pages/dws10-com/config/products.json"

CURRENT_VERSION="$(node -e "console.log(JSON.parse(require('fs').readFileSync('${CANON}','utf8')).priceList.version||'')" 2>/dev/null || true)"

if [ "${CURRENT_VERSION}" = "${NEW_VERSION}" ]; then
  echo "[price-list-gate] Already at ${NEW_VERSION}, nothing to do."
  exit 0
fi

echo "[price-list-gate] Rolling ${CURRENT_VERSION} → ${NEW_VERSION} (stamp=${NEW_STAMP_QUARTER}, valid=${STAMP_DATE}…${VALID_UNTIL})"

node -e "
const fs = require('fs');
const files = ['${CANON}', '${MIRROR}'];
files.forEach((f) => {
  const d = JSON.parse(fs.readFileSync(f,'utf8'));
  d.priceList.version = '${NEW_VERSION}';
  d.priceList.stampQuarter = '${NEW_STAMP_QUARTER}';
  d.priceList.stampDate = '${STAMP_DATE}';
  d.priceList.effectiveDate = '${STAMP_DATE}';
  d.priceList.validUntil = '${VALID_UNTIL}';
  d.priceList.nextReviewDate = '${NEXT_REVIEW}';
  d.priceList.changeLog = d.priceList.changeLog || [];
  d.priceList.changeLog.push({
    version: '${NEW_VERSION}',
    date: '${TODAY}',
    change: 'Quarterly stamp roll (auto, price-list-quarterly-gate.sh): prices valid ${STAMP_DATE}…${VALID_UNTIL}. Review any pending price edits before announcing.'
  });
  d.lastUpdated = new Date().toISOString();
  fs.writeFileSync(f, JSON.stringify(d, null, 2) + '\n', 'utf8');
});
console.log('[price-list-gate] Updated products.json × 2');
"

node scripts/gen-price-list-html.cjs

BRANCH="$(git rev-parse --abbrev-ref HEAD)"
if [ "${BRANCH}" = "main" ] || [ "${BRANCH}" = "master" ]; then
  echo "[price-list-gate] Refusing to auto-commit to ${BRANCH}. Manual PR required."
  exit 0
fi

git add \
  "${CANON}" "${MIRROR}" \
  dws10.com/price-list/versions/ \
  landing-pages/dws10-com/price-list/versions/

if git diff --cached --quiet; then
  echo "[price-list-gate] No changes to commit."
  exit 0
fi

git commit -m "Price list: quarterly stamp roll → ${NEW_VERSION} (${NEW_STAMP_QUARTER})

Auto-generated by scripts/daily/price-list-quarterly-gate.sh.
Prices valid ${STAMP_DATE} to ${VALID_UNTIL}.
Next review: ${NEXT_REVIEW}.

Email send is RED-zone: operator runs scripts/send-price-list-email.ts manually."

git push -u origin "${BRANCH}" || {
  echo "[price-list-gate] Push failed. Retry manually."
  exit 1
}

echo "[price-list-gate] Done. Snapshot price-list-v${NEW_VERSION}.html published."
echo "[price-list-gate] To dispatch to customers: node scripts/send-price-list-email.ts --version ${NEW_VERSION}"
