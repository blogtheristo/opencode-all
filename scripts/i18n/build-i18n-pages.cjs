#!/usr/bin/env node
/**
 * build-i18n-pages.cjs — generate per-language copies of an HTML page from one master.
 *
 * Generalised from the Aegis page build (scripts/i18n/build-aegis-pages.cjs) the second
 * time this was needed, per the CLAUDE.md Skill Codification Rule ("asked twice = failure").
 * Add a target by writing a config file, not by writing another script.
 *
 * Design: translation is DATA (one JSON array of the page's text nodes, in document
 * order, per language); markup manipulation is DETERMINISTIC code. Translators never
 * touch HTML, so they cannot break it. The builder refuses to write when a translation's
 * string count drifts from the master, rather than emitting a misaligned page.
 *
 * Usage:
 *   node scripts/i18n/build-i18n-pages.cjs scripts/i18n/<target>.config.json
 *
 * Config:
 *   { id, master, masterLang, stringsDir, outDirs[], urlBase, files{lang:filename},
 *     cutMarker?, shareTitleKey? }
 *   - master      path to the source page (may itself be one of the outputs)
 *   - stringsDir  holds <lang>-strings.json (a bare JSON array) per non-master language,
 *                 and optionally meta.json (see below)
 *   - outDirs     every folder the pages are written to (dual-folder rule)
 *   - cutMarker   optional: text after which content is generated by another tool
 *                 (e.g. the blog nav injector). That region is never translated, but its
 *                 URLs and share title are still retargeted to this language.
 *
 * <stringsDir>/meta.json is optional and covers what text nodes cannot: copy that lives in
 * HTML *attributes*. Shape: { "<lang>": { "description": "...", "og:description": "...",
 * "shareTitle": "..." } }. Keys match a <meta name=…> or <meta property=…>; `shareTitle` is
 * special-cased for the percent-encoded title inside injected social-share links. Without
 * it a French page ships a Finnish og:description — invisible on screen, wrong in every
 * preview card.
 *
 * Idempotent: normalises its own previous output before extracting, so re-running is safe.
 */
const fs = require('fs');
const path = require('path');

const BASE = path.resolve(__dirname, '../..');
const LABELS = {
  en: '🇬🇧 In English',
  fi: '🇫🇮 Suomeksi',
  sv: '🇸🇪 Svenska',
  de: '🇩🇪 Deutsch',
  fr: '🇫🇷 Français',
};
const LOCALES = { en: 'en_GB', fi: 'fi_FI', sv: 'sv_SE', de: 'de_DE', fr: 'fr_FR' };

function tokenize(html) {
  const masks = [];
  const masked = html.replace(/<(script|style)[\s\S]*?<\/\1>/g, (m) => {
    masks.push(m);
    return ` MASK${masks.length - 1} `;
  });
  return { parts: masked.split(/(<[^>]+>)/), masks };
}

const translatable = (p) =>
  !!p &&
  !p.startsWith('<') &&
  !p.includes(' MASK') &&
  p.trim().length > 1 &&
  !/^[\W\d\s&;]+$/.test(p.trim());

/**
 * EU AI Act Article 50(4) disclosure for machine-translated pages.
 *
 * The duty is on the deployer (us) and applies from 2 August 2026 to AI-generated or
 * manipulated text published to inform the public on matters of public interest. It falls
 * away only where a named person took editorial responsibility after a substantive review
 * before publication — so this notice is the floor, not the goal. When a language IS
 * reviewed, drop it from `aiNotice.langs` and credit the reviewer on the page instead.
 * Canonical: DWS_TRUTH_STANDARD.md §2 row 31 / §2G.
 *
 * Deliberately NOT included: the Commission's official EU Icon. It is optional, and
 * ec.europa.eu blocks automated download — inventing a lookalike would misrepresent an
 * official mark. Drop the real asset in and reference it here once a human has fetched it.
 */
function aiNotice(cfg, lang, meta) {
  const m = (meta && meta[lang]) || {};
  if (!m.aiNoticeLabel || !m.aiNoticeBody) {
    throw new Error(`${lang}: aiNotice requested but aiNoticeLabel/aiNoticeBody missing from meta.json`);
  }
  const href = urlFor(cfg, cfg.masterLang).replace(/^https?:\/\/[^/]+/, '');
  const link = m.aiNoticeLink
    ? `\n            <a href="${href}" hreflang="${cfg.masterLang}" lang="${cfg.masterLang}" style="color:#22d3ee;text-decoration:underline">${m.aiNoticeLink} &rarr;</a>`
    : '';
  // aria-label carries the disclosure for assistive technology, per the Code's accessibility
  // guidance ("readable by assistive technologies using alt text or ARIA labels indicating that
  // the content is AI-generated or manipulated") — role="note" alone announces nothing useful.
  return (
    `\n        <aside class="ai-notice" role="note" aria-label="${m.aiNoticeLabel}" style="margin:0 0 1.75rem;padding:0.85rem 1.1rem;border-left:3px solid #94a3b8;background:rgba(30,41,59,0.55);color:#cbd5e1;font-size:0.85rem;line-height:1.6">\n` +
    `          <strong style="color:#f1f5f9">${m.aiNoticeLabel}</strong> &middot; ${m.aiNoticeBody}${link}\n` +
    `        </aside>\n`
  );
}

/** Remove everything this builder injects, so its own output normalises back to a master. */
function normalize(html) {
  return html
    .replace(/\n {8}<aside class="ai-notice"[\s\S]*?<\/aside>\n/g, '')
    .replace(/\n {4}<nav class="i18n-links"[\s\S]*?<\/nav>\n/g, '')
    .replace(
      / {4}<link\n {6}rel="alternate"\n {6}hreflang="[^"]*"\n {6}href="[^"]*"\n {4}\/>\n/g,
      '',
    );
}

function extract(html) {
  return tokenize(html)
    .parts.filter(translatable)
    .map((p) => p.trim());
}

function applyTranslations(html, translated) {
  const { parts, masks } = tokenize(html);
  let i = 0;
  const out = parts
    .map((p) => {
      if (!translatable(p)) return p;
      const t = translated[i++];
      if (t === undefined) throw new Error('ran out of translations');
      return p.match(/^\s*/)[0] + t + p.match(/\s*$/)[0];
    })
    .join('')
    .replace(/ MASK(\d+) /g, (_, n) => masks[Number(n)]);
  if (i !== translated.length) {
    throw new Error(`translation count mismatch: consumed ${i}, provided ${translated.length}`);
  }
  return out;
}

function urlFor(cfg, lang) {
  return cfg.urlBase + cfg.files[lang];
}

/**
 * Replace the `content` of <meta name="k"> / <meta property="k"> for each key in `meta`.
 * A key written as a full attribute (`aria-label="Valikko"`) is instead replaced literally,
 * which covers the handful of translatable strings that live outside text nodes.
 */
function applyMeta(html, meta) {
  let out = html;
  Object.entries(meta || {}).forEach(([key, value]) => {
    // Keys consumed elsewhere: shareTitle by retargetTail, aiNotice* by aiNotice().
    if (key === 'shareTitle' || key.startsWith('aiNotice')) return;
    if (/["<>]/.test(value)) throw new Error(`meta ${key}: value must not contain " < >`);
    if (key.includes('="')) {
      const attr = key.slice(0, key.indexOf('='));
      if (!out.includes(key)) throw new Error(`attr ${key}: not present in the master`);
      out = out.split(key).join(`${attr}="${value}"`);
      return;
    }
    const re = new RegExp(
      `(<meta\\s*\\n?\\s*(?:name|property)="${key.replace(/[.*+?^$()|[\\]\\\\]/g, '\\\\$&')}"\\s*\\n?\\s*content=")[^"]*(")`,
    );
    if (!re.test(out)) throw new Error(`meta ${key}: no matching <meta> tag in the master`);
    out = out.replace(re, `$1${value}$2`);
  });
  return out;
}

/**
 * The tail is generated by another tool and never translated, but it still embeds this
 * post's own URL (canonical, copy-link, share links) and its headline. Retarget both so a
 * translated page shares itself, not the master.
 */
function retargetTail(tail, cfg, lang, shareTitles) {
  if (!tail) return tail;
  const from = cfg.files[cfg.masterLang];
  const to = cfg.files[lang];
  let out = from === to ? tail : tail.split(from).join(to);

  const fromTitle = shareTitles[cfg.masterLang];
  const toTitle = shareTitles[lang];
  if (fromTitle && toTitle && fromTitle !== toTitle) {
    // Share links carry the title percent-encoded; the raw form appears in prev/next text.
    out = out.split(encodeURIComponent(fromTitle)).join(encodeURIComponent(toTitle));
    out = out.split(fromTitle).join(toTitle);
  }
  return out;
}

function hreflangBlock(cfg) {
  const langs = Object.keys(cfg.files);
  const order = ['en', 'fi', 'sv', 'fr', 'de'].filter((l) => langs.includes(l));
  const xDefault = langs.includes('en') ? 'en' : cfg.masterLang;
  return (
    order
      .map(
        (l) =>
          `    <link\n      rel="alternate"\n      hreflang="${l}"\n      href="${urlFor(cfg, l)}"\n    />`,
      )
      .join('\n') +
    `\n    <link\n      rel="alternate"\n      hreflang="x-default"\n      href="${urlFor(cfg, xDefault)}"\n    />`
  );
}

function langSwitcher(cfg, lang) {
  const links = Object.keys(cfg.files)
    .filter((l) => l !== lang)
    .map(
      (l) =>
        `      <a href="${urlFor(cfg, l).replace(/^https?:\/\/[^/]+/, '')}" hreflang="${l}" lang="${l}" style="margin:0 8px;color:inherit">${LABELS[l] || l}</a>`,
    )
    .join('\n');
  return `    <nav class="i18n-links" aria-label="Language" style="text-align:center;padding:18px 12px;font-size:0.85rem;opacity:0.75">\n${links}\n    </nav>\n`;
}

function retarget(html, cfg, lang, meta) {
  let out = normalize(html);
  const url = urlFor(cfg, lang);

  // Article 50(4) disclosure, before the article body — the reader must see it on first
  // exposure, not after scrolling past the text it applies to.
  if (cfg.aiNotice && cfg.aiNotice.langs.includes(lang)) {
    const anchor = cfg.aiNotice.after || '</header>';
    if (!out.includes(anchor)) throw new Error(`${lang}: aiNotice anchor ${anchor} not found`);
    out = out.replace(anchor, anchor + aiNotice(cfg, lang, meta));
  }

  out = out.replace(/<html lang="[a-z-]+"/, `<html lang="${lang}"`);
  out = out.replace(
    /( *<link\s*\n?\s*rel="canonical"\s*\n?\s*href=")[^"]*(")/,
    (m) => m.replace(/href="[^"]*"/, `href="${url}"`),
  );
  // canonical may be single-line in some pages
  out = out.replace(/<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${url}" />`);

  // insert hreflang once, right after the canonical link
  if (!/hreflang="x-default"/.test(out)) {
    out = out.replace(
      /(<link\s*\n?\s*rel="canonical"[\s\S]*?\/>)/,
      `$1\n${hreflangBlock(cfg)}`,
    );
  }

  out = out.replace(/(<meta property="og:locale" content=")[^"]*(")/, `$1${LOCALES[lang]}$2`);
  out = out.replace(
    /(<meta\s*\n?\s*property="og:url"\s*\n?\s*content=")[^"]*(")/,
    (m) => m.replace(/content="[^"]*"/, `content="${url}"`),
  );

  if (!/class="i18n-links"/.test(out)) {
    out = out.replace(/(\n\s*<\/body>)/, `\n${langSwitcher(cfg, lang)}$1`);
  }
  return out;
}

function main() {
  const cfgPath = process.argv[2];
  if (!cfgPath) throw new Error('usage: build-i18n-pages.cjs <config.json>');
  const cfg = JSON.parse(fs.readFileSync(path.resolve(BASE, cfgPath), 'utf8'));

  const masterRaw = fs.readFileSync(path.join(BASE, cfg.master), 'utf8');
  // Content after cutMarker is generated by another tool — never translated, never emitted here.
  const cut = cfg.cutMarker ? masterRaw.indexOf(cfg.cutMarker) : -1;
  const head = normalize(cut === -1 ? masterRaw : masterRaw.slice(0, cut));
  const tail = cut === -1 ? '' : masterRaw.slice(cut);

  const masterStrings = extract(head);
  console.log(`[i18n:${cfg.id}] master (${cfg.masterLang}) text nodes: ${masterStrings.length}`);

  const metaPath = path.join(BASE, cfg.stringsDir, 'meta.json');
  const meta = fs.existsSync(metaPath) ? JSON.parse(fs.readFileSync(metaPath, 'utf8')) : {};
  const shareTitles = Object.fromEntries(
    Object.entries(meta).map(([l, m]) => [l, m.shareTitle]),
  );

  // The master keeps its own text and meta; only its URL-level tags are (re)stamped.
  const builds = [[cfg.masterLang, head, tail]];

  Object.keys(cfg.files)
    .filter((l) => l !== cfg.masterLang)
    .forEach((lang) => {
      const file = path.join(BASE, cfg.stringsDir, `${lang}-strings.json`);
      if (!fs.existsSync(file)) {
        console.log(`[i18n:${cfg.id}] SKIP ${lang} — ${cfg.stringsDir}/${lang}-strings.json missing`);
        return;
      }
      const translated = JSON.parse(fs.readFileSync(file, 'utf8'));
      if (!Array.isArray(translated)) throw new Error(`${lang}: expected a JSON array`);
      if (translated.length !== masterStrings.length) {
        throw new Error(
          `${lang}: string count mismatch — master ${masterStrings.length}, translation ${translated.length}`,
        );
      }
      builds.push([lang, applyMeta(applyTranslations(head, translated), meta[lang]), tail]);
    });

  builds.forEach(([lang, body, rawTail]) => {
    // retarget last, on the whole document: the language switcher goes before </body>,
    // which lives in the tail.
    const html = retarget(body + retargetTail(rawTail, cfg, lang, shareTitles), cfg, lang, meta);
    cfg.outDirs.forEach((dir) => {
      const abs = path.join(BASE, dir);
      fs.mkdirSync(abs, { recursive: true });
      fs.writeFileSync(path.join(abs, cfg.files[lang]), html, 'utf8');
    });
    console.log(`[i18n:${cfg.id}] wrote ${cfg.files[lang]} (${html.length} bytes) × ${cfg.outDirs.length}`);
  });
}

main();
